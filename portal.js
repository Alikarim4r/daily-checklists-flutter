  const apply = () => {
    const lang = localStorage.getItem("dc-lang") || "ar";
    const theme = localStorage.getItem("dc-theme") || "light";
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.dataset.theme = theme === "dark" ? "dark" : "";
    const dict = I18N[lang] || I18N.ar;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) el.textContent = dict[key];
    });
    document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
      btn.textContent = dict.langToggle;
    });
    document.querySelectorAll("[data-theme-toggle]").forEach((btn) => {
      btn.textContent = theme === "dark" ? (lang === "ar" ? "فاتح" : "Light") : dict.themeToggle;
    });
  };

  document.addEventListener("click", (e) => {
    const langBtn = e.target.closest("[data-lang-toggle]");
    if (langBtn) {
      const cur = localStorage.getItem("dc-lang") || "ar";
      localStorage.setItem("dc-lang", cur === "ar" ? "en" : "ar");
      apply();
    }
    const themeBtn = e.target.closest("[data-theme-toggle]");
    if (themeBtn) {
      const cur = localStorage.getItem("dc-theme") || "light";
      localStorage.setItem("dc-theme", cur === "dark" ? "light" : "dark");
      apply();
    }
  });

  apply();
