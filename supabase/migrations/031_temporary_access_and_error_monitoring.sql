-- Expiring site grants + privacy-conscious structured client error monitoring.

alter table public.user_site_access
  add column if not exists valid_from timestamptz,
  add column if not exists valid_until timestamptz;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'user_site_access_valid_window'
  ) then
    alter table public.user_site_access
      add constraint user_site_access_valid_window
      check (
        valid_from is null or valid_until is null or valid_until > valid_from
      );
  end if;
end;
$$;

create index if not exists user_site_access_validity_idx
  on public.user_site_access (user_id, site_id, valid_from, valid_until);

create or replace function public.site_access_grant_is_current(
  p_valid_from timestamptz,
  p_valid_until timestamptz
)
returns boolean
language sql
stable
set search_path = public
as $$
  select (p_valid_from is null or p_valid_from <= now())
    and (p_valid_until is null or p_valid_until > now())
$$;

create or replace function public.has_site_access(p_site_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
set row_security = off
as $$
  select
    public.is_platform_owner()
    or exists (
      select 1 from public.sites site
      where site.id = p_site_id
        and public.is_org_super_admin(site.organization_id)
    )
    or (
      public.is_approved_active_user()
      and exists (
        select 1
        from public.user_site_access access_row
        left join public.sites child on child.id = p_site_id
        where access_row.user_id = auth.uid()
          and access_row.can_read
          and public.site_access_grant_is_current(
            access_row.valid_from, access_row.valid_until
          )
          and (
            access_row.site_id = p_site_id
            or (
              child.parent_site_id is not null
              and access_row.site_id = child.parent_site_id
            )
          )
      )
    );
$$;

