-- Client logs deliberately exclude payloads, access tokens, evidence and user
-- entered form data. They are owner-readable and user-insert-only.
create table if not exists public.client_error_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete restrict,
  app_key text not null,
  app_version text not null default '',
  build_number text not null default '',
  platform text not null default '',
  module text not null default '',
  error_type text not null default '',
  error_message text not null default '',
  stack_summary text not null default '',
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint client_error_logs_message_length
    check (length(error_message) <= 2000 and length(stack_summary) <= 6000)
);

create index if not exists client_error_logs_recent_idx
  on public.client_error_logs (occurred_at desc);
create index if not exists client_error_logs_app_idx
  on public.client_error_logs (app_key, occurred_at desc);

alter table public.client_error_logs enable row level security;
revoke all on public.client_error_logs from anon, authenticated;
grant insert, select on public.client_error_logs to authenticated;
grant usage, select on sequence public.client_error_logs_id_seq to authenticated;

drop policy if exists client_error_logs_insert_own on public.client_error_logs;
create policy client_error_logs_insert_own
  on public.client_error_logs for insert to authenticated
  with check (user_id = auth.uid());

drop policy if exists client_error_logs_owner_select on public.client_error_logs;
create policy client_error_logs_owner_select
  on public.client_error_logs for select to authenticated
  using (public.is_platform_owner());
