-- GLOB-001 P2 completion: autonomous, tenant-safe, bounded job materialization.
-- Intended to run as the database owner via pg_cron hourly. This migration
-- does not install pg_cron (the installation/schedule is in the next migration).
create table if not exists public.fm_ppm_scheduler_runs (
  id bigint generated always as identity primary key,
  executed_at timestamptz not null default clock_timestamp(),
  generated_jobs integer not null,
  examined_plans integer not null,
  processing_ms integer not null
);
alter table public.fm_ppm_scheduler_runs enable row level security;
revoke all on public.fm_ppm_scheduler_runs from public, anon, authenticated;
grant select on public.fm_ppm_scheduler_runs to authenticated;
create policy fm_ppm_scheduler_owner_read
  on public.fm_ppm_scheduler_runs for select to authenticated
  using (public.is_platform_owner());
create index if not exists fm_ppm_scheduler_recent_idx
 on public.fm_ppm_scheduler_runs(executed_at desc);

create or replace function public.fm_ppm_scheduler_tick()
returns integer language plpgsql volatile security definer
set search_path = public,pg_temp as $$
declare
  v_start timestamptz := clock_timestamp();
  v_plan record;
  v_asset public.fm_assets%rowtype;
  v_today date;
  v_due date;
  v_next_index integer;
  v_new_job uuid;
  v_generated integer := 0;
  v_examined integer := 0;
begin
  -- The routine is a privileged backend operation; client sessions may
  -- never invoke it, even through a SECURITY DEFINER wrapper.
  if session_user <> 'postgres' then
    raise exception 'background scheduler requires postgres role'
      using errcode='42501';
  end if;

  -- Bounded global work to keep cron runs cheap under growing tenant load.
  for v_plan in
    select p.* from public.fm_ppm_plans p
      join public.fm_assets a on a.id=p.asset_id
    where p.is_active and a.status<>'retired'
      and p.next_due_on <=
        (clock_timestamp() at time zone p.timezone_id)::date + 45
    order by p.next_due_on,p.id
    for update of p skip locked
    limit 1500
  loop
    v_examined := v_examined + 1;
    select * into v_asset from public.fm_assets where id=v_plan.asset_id;
    v_today := (clock_timestamp() at time zone v_plan.timezone_id)::date;
    v_due := v_plan.next_due_on;
    v_next_index := v_plan.occurrence_index;
    while v_due <= v_today + 45 and v_generated<3000 loop
      v_new_job:=null;
      insert into public.fm_ppm_jobs (
        organization_id,plan_id,asset_id,site_id,
        checklist_assignment_id,due_on)
      values (
        v_plan.organization_id,v_plan.id,v_plan.asset_id,
        v_asset.site_id,v_plan.checklist_assignment_id,v_due)
      on conflict (plan_id,due_on) do nothing
      returning id into v_new_job;
      if v_new_job is not null then
        insert into public.fm_ppm_job_events
          (organization_id,job_id,action,actor_id,notes)
        values(v_plan.organization_id,v_new_job,'created',null,
               'Generated by hourly PPM background scheduler');
        v_generated:=v_generated+1;
      end if;
      v_next_index:=v_next_index+1;
      v_due:=public.fm_ppm_due_date(
        v_plan.anchor_date,v_plan.frequency,
        v_plan.interval_count,v_next_index);
      if v_next_index>20000 then
        raise exception 'PPM plan % reached safety limit',v_plan.id;
      end if;
    end loop;
    update public.fm_ppm_plans
       set occurrence_index=v_next_index,next_due_on=v_due
     where id=v_plan.id;
    exit when v_generated>=3000;
  end loop;

  insert into public.fm_ppm_scheduler_runs
   (generated_jobs,examined_plans,processing_ms)
  values(v_generated,v_examined,
    least(2147483647,ceil(extract(epoch from clock_timestamp()-v_start)*1000)::integer));
  return v_generated;
end;
$$;
revoke all on function public.fm_ppm_scheduler_tick() from public,anon,authenticated;
-- The owner (postgres) retains EXECUTE. Never grant to authenticated/service apps.
