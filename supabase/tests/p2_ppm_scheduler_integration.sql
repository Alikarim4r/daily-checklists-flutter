-- P2 autonomous scheduler integration tests, disposable isolated PG only.
set role authenticated;
set request.jwt.claim.sub='10000000-0000-0000-0000-000000000001';
do $$
declare denied boolean := false;
begin
  begin
    perform public.fm_ppm_scheduler_tick();
  exception when insufficient_privilege then denied:=true;
  end;
  if not denied then
    raise exception 'authenticated account must NEVER be able to call scheduler';
  end if;
end $$;
reset role;

do $$
declare first_created int; again_created int; from_audit int;
begin
  first_created := public.fm_ppm_scheduler_tick();
  if first_created < 1 or first_created > 3000 then
    raise exception 'unexpected initial scheduled jobs generated: %',first_created;
  end if;
  again_created := public.fm_ppm_scheduler_tick();
  if again_created <> 0 then
    raise exception 'hourly scheduler repeated jobs: %',again_created;
  end if;
  select generated_jobs into from_audit
  from public.fm_ppm_scheduler_runs order by id desc limit 1;
  if from_audit <> 0 then raise exception 'missing zero-change heartbeat'; end if;
  if (select count(*) from public.fm_ppm_job_events where action='created'
        and actor_id is null and notes like 'Generated by hourly%') <> first_created then
    raise exception 'scheduler event audit missing'; end if;
end $$;
select 'P2 HOURLY AUTONOMOUS SCHEDULER RLS + IDEMPOTENCY PASS' as result;
